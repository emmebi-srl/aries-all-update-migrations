-- 1. Settings of a campaign type for a customer type. A missing row means the defaults (every channel
--    enabled). invio_whatsapp = 0: the customers of that type don't get the WhatsApp channel of the
--    campaigns of that type, only the email. No foreign key to tipo_cliente: legacy table written by
--    Delphi, its rows are only read here.
CREATE TABLE IF NOT EXISTS `tipo_campagna_aries_tipo_cliente` (
	`id_tipo_campagna` INT(11) NOT NULL,
	`id_tipo_cliente` INT(11) NOT NULL COMMENT 'tipo_cliente.Id_tipo',
	`invio_whatsapp` TINYINT(1) NOT NULL DEFAULT 1 COMMENT '0 = solo email per questo tipo cliente',
	PRIMARY KEY (`id_tipo_campagna`, `id_tipo_cliente`) USING BTREE,
	INDEX `idx_tipo_campagna_aries_tipo_cliente_cliente` (`id_tipo_cliente`) USING BTREE,
	CONSTRAINT `FK_tipo_campagna_aries_tipo_cliente_tipo` FOREIGN KEY (`id_tipo_campagna`) REFERENCES `tipo_campagna_aries` (`id`) ON UPDATE CASCADE ON DELETE CASCADE
)
COLLATE='latin1_swedish_ci'
ENGINE=InnoDB;

--    For now the invoices statement doesn't go on WhatsApp to private customers (tipo_cliente PRIVATO,
--    matched by name because the ids may differ between companies). INSERT IGNORE: a rerun doesn't
--    override a row changed later from the web app.
INSERT IGNORE INTO `tipo_campagna_aries_tipo_cliente` (`id_tipo_campagna`, `id_tipo_cliente`, `invio_whatsapp`)
SELECT t.`id`, c.`Id_tipo`, 0
FROM `tipo_campagna_aries` t
  INNER JOIN `tipo_cliente` c ON UPPER(TRIM(c.`nome`)) = 'PRIVATO'
WHERE t.`rif_applicazione` = 'customer_invoices_statement';

-- 2. WhatsApp can't show the email: a campaign can send its email body as a PDF in the document header
--    of the WhatsApp template when the dispatch has no attachment (the first attachment, e.g. the
--    invoices statement, always wins). The PDF is generated by
--    the WhatsApp sender from the resolved HTML template and is not attached to the email. The file
--    name can use the placeholders ({{customer_name}}, ...); empty = the email subject.
SET @campaign_whatsapp_pdf_exists = (
  SELECT COUNT(*) FROM information_schema.COLUMNS
  WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'campagna_aries'
    AND COLUMN_NAME = 'whatsapp_pdf_mail'
);
SET @campaign_whatsapp_pdf_sql = IF(
  @campaign_whatsapp_pdf_exists > 0,
  'SELECT 1',
  'ALTER TABLE `campagna_aries` ADD COLUMN `whatsapp_pdf_mail` TINYINT(1) NOT NULL DEFAULT 0 COMMENT ''Documento WhatsApp = corpo della mail in PDF'' AFTER `id_template_whatsapp`'
);
PREPARE campaign_whatsapp_pdf_statement FROM @campaign_whatsapp_pdf_sql;
EXECUTE campaign_whatsapp_pdf_statement;
DEALLOCATE PREPARE campaign_whatsapp_pdf_statement;

--    For now only the subscription campaigns send the email PDF (their dispatches have no attachment).
--    Set only when the column is created: a rerun doesn't override a later choice.
SET @campaign_whatsapp_pdf_default_sql = IF(
  @campaign_whatsapp_pdf_exists > 0,
  'SELECT 1',
  'UPDATE `campagna_aries` c INNER JOIN `tipo_campagna_aries` t ON t.`id` = c.`id_tipo_campagna` SET c.`whatsapp_pdf_mail` = 1 WHERE t.`rif_applicazione` = ''system_subscription'''
);
PREPARE campaign_whatsapp_pdf_default_statement FROM @campaign_whatsapp_pdf_default_sql;
EXECUTE campaign_whatsapp_pdf_default_statement;
DEALLOCATE PREPARE campaign_whatsapp_pdf_default_statement;

SET @campaign_whatsapp_pdf_name_sql = IF(
  EXISTS (
    SELECT 1 FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'campagna_aries'
      AND COLUMN_NAME = 'whatsapp_nome_file_pdf_mail'
  ),
  'SELECT 1',
  'ALTER TABLE `campagna_aries` ADD COLUMN `whatsapp_nome_file_pdf_mail` VARCHAR(150) NULL DEFAULT NULL COMMENT ''Nome del PDF, con segnaposto; vuoto = oggetto della mail'' AFTER `whatsapp_pdf_mail`'
);
PREPARE campaign_whatsapp_pdf_name_statement FROM @campaign_whatsapp_pdf_name_sql;
EXECUTE campaign_whatsapp_pdf_name_statement;
DEALLOCATE PREPARE campaign_whatsapp_pdf_name_statement;

-- 3. Subscription campaigns: system type placeholder (tipo_impianto description), filled when the
--    dispatch is created. 11 characters, also usable as WhatsApp variable.
INSERT INTO `campagna_aries_segnaposto` (`uuid`, `id_tipo_campagna`, `nome`, `descrizione`, `valore_predefinito`)
SELECT UUID(), t.`id`, 'system_type', 'Tipo Impianto', ''
FROM `tipo_campagna_aries` t
WHERE t.`rif_applicazione` = 'system_subscription'
  AND NOT EXISTS (
    SELECT 1 FROM `campagna_aries_segnaposto` s
    WHERE s.`id_tipo_campagna` = t.`id` AND s.`nome` = 'system_type'
  );
